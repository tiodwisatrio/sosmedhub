    public function index()
    {
        $menus = Menu::whereNull('parent_id')
            ->with(['children' => fn ($q) => $q->orderBy('urutan')])
            ->orderBy('urutan')
            ->get();

        return view('menu::admin.index', compact('menus'));
    }

    public function create()
    {
        $parents = Menu::whereNull('parent_id')->orderBy('urutan')->get();

        return view('menu::admin.create', ['parents' => $parents, 'icons' => self::$icons]);
    }

    public function store(StoreMenuRequest $request)
    {
        $data = $request->validated();
        $data['route_params'] = $this->parseRouteParams($request->input('route_params'));

        Menu::create($data);

        return redirect()->route('admin.menus.index')
            ->with('success', 'Menu berhasil ditambahkan.');
    }

    public function edit(Menu $menu)
    {
        $parents = Menu::whereNull('parent_id')
            ->where('id', '!=', $menu->id)
            ->orderBy('urutan')
            ->get();

        return view('menu::admin.edit', ['menu' => $menu, 'parents' => $parents, 'icons' => self::$icons]);
    }

    public function update(UpdateMenuRequest $request, Menu $menu)
    {
        $data = $request->validated();
        $data['route_params'] = $this->parseRouteParams($request->input('route_params'));

        $menu->update($data);

        return redirect()->route('admin.menus.index')
            ->with('success', 'Menu berhasil diperbarui.');
    }

    public function destroy(Menu $menu)
    {
        $menu->children()->delete();
        $menu->delete();

        return redirect()->route('admin.menus.index')
            ->with('success', 'Menu berhasil dihapus.');
    }

    public function reorder(Request $request)
    {
        $request->validate([
            'items' => ['required', 'array'],
            'items.*.id' => ['required', 'exists:menus,id'],
            'items.*.urutan' => ['required', 'integer'],
            'items.*.parent_id' => ['nullable', 'integer', 'exists:menus,id'],
        ]);

        foreach ($request->items as $item) {
            $data = ['urutan' => $item['urutan']];
            if (array_key_exists('parent_id', $item)) {
                $data['parent_id'] = $item['parent_id'];
            }
            Menu::where('id', $item['id'])->update($data);
        }

        return response()->json(['ok' => true]);
    }

    private function parseRouteParams(?string $raw): ?array
    {
        if (! $raw || trim($raw) === '') {
            return null;
        }

        $decoded = json_decode($raw, true);
        if (json_last_error() === JSON_ERROR_NONE) {
            return $decoded;
        }

        // Support simple key=value format: type=team
        $params = [];
        foreach (explode('&', $raw) as $pair) {
            [$k, $v] = array_pad(explode('=', $pair, 2), 2, '');
            if ($k) {
                $params[trim($k)] = trim($v);
            }
        }

        return $params ?: null;
    }
